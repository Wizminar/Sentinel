import { fixesFor, renderConfig } from "./remediation.js";
import type { Report, Severity, Status } from "./types.js";

const ICON: Record<Status, string> = { pass: "✅", warn: "⚠️", fail: "❌", info: "ℹ️" };

export function toMarkdown(r: Report): string {
  const out: string[] = [];
  out.push(`## Sentinel: ${r.grade} (${r.score}/100) — ${r.finalUrl}`, "");
  if (r.cap) out.push(`> Grade capped at **${r.cap.grade}**: ${r.cap.reason}`, "");
  out.push("| | Check | Result | Points |", "|---|---|---|---:|");
  for (const c of r.checks) {
    out.push(`| ${ICON[c.status]} | ${c.title} | ${c.summary.replace(/\|/g, "\\|")} | ${c.modifier > 0 ? "+" : ""}${c.modifier} |`);
  }
  const issues = r.checks.flatMap((c) => c.findings.filter((f) => f.modifier < 0).map((f) => `- **${c.title}:** ${f.message}`));
  if (issues.length) out.push("", "### What to fix", "", ...issues);
  const fixes = fixesFor(r);
  if (fixes.length) out.push("", "<details><summary>nginx config</summary>", "", "```nginx", renderConfig("nginx", fixes), "```", "", "</details>");
  out.push("", `<sub>Generated by Sentinel ${r.engine} at ${r.generatedAt}</sub>`);
  return out.join("\n");
}

const SARIF_LEVEL: Record<Severity, "error" | "warning" | "note"> = {
  critical: "error", high: "error", medium: "warning", low: "note", info: "note",
};

/** SARIF 2.1.0, for GitHub code scanning and other static-analysis dashboards. */
export function toSarif(r: Report) {
  const findings = r.checks.flatMap((c) => c.findings.filter((f) => f.modifier < 0).map((f) => ({ c, f })));
  const rules = [...new Map(findings.map(({ c, f }) => [f.id, {
    id: f.id,
    name: f.id.replace(/[^a-z0-9]+/gi, "_"),
    shortDescription: { text: `${c.title}: ${f.message}` },
    helpUri: "https://github.com/Wizminar/Sentinel#checks",
    properties: { tags: ["security", "http-headers"], "security-severity": { critical: "9.5", high: "7.5", medium: "5.0", low: "3.0", info: "0.0" }[f.severity] },
  }])).values()];
  return {
    $schema: "https://json.schemastore.org/sarif-2.1.0.json",
    version: "2.1.0",
    runs: [{
      tool: { driver: { name: "Sentinel", version: r.engine, informationUri: "https://github.com/Wizminar/Sentinel", rules } },
      results: findings.map(({ f }) => ({
        ruleId: f.id,
        level: SARIF_LEVEL[f.severity],
        message: { text: f.message + (f.evidence ? ` Evidence: ${f.evidence}` : "") },
        locations: [{ physicalLocation: { artifactLocation: { uri: r.finalUrl } } }],
      })),
    }],
  };
}
